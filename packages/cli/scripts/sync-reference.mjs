import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const manifest = JSON.parse(readFileSync(resolve(root, "src/operation-manifest.json"), "utf8"));
const reference = [
  "| Command | SDK method | Inputs |",
  "| --- | --- | --- |",
  ...manifest.map((row) => {
    const inputs = [
      ...row.parameters.map((p) => p.cliFlagOrArgument),
      ...(row.argument ? [row.argument] : []),
      ...Object.values(row.body?.primaryFlags ?? {}),
      ...(row.body ? ["--data"] : []),
      ...(row.pagination !== "none" ? ["--all"] : []),
      ...(row.destructive ? ["--yes"] : []),
    ];
    return `| \`creem ${row.cliPath}\` | \`${row.sdkMethod}\` | ${inputs.map((v) => "`" + v + "`").join(", ")} |`;
  }),
].join("\n");
for (const name of ["README.md", "AGENTS.md"]) {
  const path = resolve(root, name);
  const original = readFileSync(path, "utf8");
  const next = original.replace(
    /<!-- CLI-REFERENCE:START -->[\s\S]*?<!-- CLI-REFERENCE:END -->/,
    `<!-- CLI-REFERENCE:START -->\n${reference}\n<!-- CLI-REFERENCE:END -->`,
  );
  if (process.argv.includes("--check")) {
    if (original !== next)
      throw new Error(`${name} command reference is stale. Run node scripts/sync-reference.mjs.`);
  } else writeFileSync(path, next);
}
const snippet = resolve(root, "../docs/snippets/cli-reference.mdx");
const content = `{/* Generated by packages/cli/scripts/sync-reference.mjs. */}\n\n${reference}\n`;
if (process.argv.includes("--check")) {
  if (readFileSync(snippet, "utf8") !== content)
    throw new Error("Public CLI command reference is stale.");
} else writeFileSync(snippet, content);
