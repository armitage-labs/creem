import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const manifest = JSON.parse(readFileSync(resolve(root, "src/operation-manifest.json"), "utf8"));
const reference = [
  "| Command | Inputs |",
  "| --- | --- |",
  ...manifest.map((row) => {
    const inputs = [
      ...row.parameters.map((p) => p.cliFlagOrArgument),
      ...(row.argument ? [row.argument] : []),
      ...Object.values(row.body?.primaryFlags ?? {}),
      ...(row.body ? ["--data"] : []),
      ...(row.pagination !== "none" ? ["--all"] : []),
      ...(row.destructive ? ["--yes"] : []),
    ];
    return `| \`creem ${row.cliPath}\` | ${inputs.map((v) => "`" + v + "`").join(", ")} |`;
  }),
].join("\n");
const snippet = resolve(root, "../docs/snippets/cli-reference.mdx");
const content = await format(
  `{/* Generated by packages/cli/scripts/sync-reference.mjs. */}\n\n${reference}\n`,
  { ...(await resolveConfig(snippet)), filepath: snippet },
);
if (process.argv.includes("--check")) {
  if (readFileSync(snippet, "utf8") !== content)
    throw new Error("Public CLI command reference is stale.");
} else writeFileSync(snippet, content);
